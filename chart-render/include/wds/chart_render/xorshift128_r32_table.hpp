// mix3 hash: seed xorshift128 with (a, b, c), run 32 rounds, then a murmur3
// fmix32 finalizer. The rounds are XOR/shift only (applied as 16 byte
// lookups), so without the finalizer mix3(s, e, k1) ^ mix3(s, e, k2) is the
// same constant for every seed s and every salt pair draws locked values.
// live dump hop (not 2022.3): Unity birth randoms of different modules are
// independent (Custom1 vs startColor Pearson 0.042, SOL axes not ±1); equal
// salts still share one value.
inline uint32_t xorshift128_r32_mix3(uint32_t a, uint32_t b, uint32_t c) noexcept {
  const uint32_t x = a != 0 ? a : 123456789u;
  const uint32_t y = b != 0 ? b : 362436069u;
  const uint32_t z = c != 0 ? c : 521288629u;
  uint32_t w = 88675123u ^ x ^ y ^ z;
  if (w == 0) {
    w = 88675123u;
  }
  const auto& t = detail::kXorshift128R32Table;
  uint32_t h = t[0][x & 0xFFu] ^ t[1][(x >> 8) & 0xFFu] ^ t[2][(x >> 16) & 0xFFu] ^
               t[3][x >> 24] ^ t[4][y & 0xFFu] ^ t[5][(y >> 8) & 0xFFu] ^
               t[6][(y >> 16) & 0xFFu] ^ t[7][y >> 24] ^ t[8][z & 0xFFu] ^
               t[9][(z >> 8) & 0xFFu] ^ t[10][(z >> 16) & 0xFFu] ^ t[11][z >> 24] ^
               t[12][w & 0xFFu] ^ t[13][(w >> 8) & 0xFFu] ^ t[14][(w >> 16) & 0xFFu] ^
               t[15][w >> 24];
  h ^= h >> 16;
  h *= 0x85EBCA6Bu;
  h ^= h >> 13;
  h *= 0xC2B2AE35u;
  h ^= h >> 16;
  return h;
}

