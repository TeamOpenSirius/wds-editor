const Glyph& glyph(char character) noexcept {
  const unsigned char input = static_cast<unsigned char>(character);
  if (input == ' ') return kBlank;
  switch (input) {
    case '%':
      return kPercent;
    case '(':
      return kParenL;
    case ')':
      return kParenR;
    case ',':
      return kComma;
    case '!':
      return kExclaim;
    case '=':
      return kEqual;
    case '_':
      return kUnderscore;
    case '<':
      return kLt;
    case '>':
      return kGt;
    case '[':
      return kBracketL;
    case ']':
      return kBracketR;
    case '\'':
    case '"':
      return kQuote;
    case '#':
      return kHash;
    case '.':
      return kDot;
    case '-':
      return kDash;
    case '+':
      return kPlus;
    case '/':
      return kSlash;
    case ':':
      return kColon;
    case '?':
      return kQuestion;
    default:
      break;
  }
  const char c = static_cast<char>(std::toupper(input));
  switch (c) {
    case 'A':
      return kA;
    case 'B':
      return kB;
    case 'C':
      return kC;
    case 'D':
      return kD;
    case 'E':
      return kE;
    case 'F':
      return kF;
    case 'G':
      return kG;
    case 'H':
      return kH;
    case 'I':
      return kI;
    case 'J':
      return kJ;
    case 'K':
      return kK;
    case 'L':
      return kL;
    case 'M':
      return kM;
    case 'N':
      return kN;
    case 'O':
      return kO;
    case 'P':
      return kP;
    case 'Q':
      return kQ;
    case 'R':
      return kR;
    case 'S':
      return kS;
    case 'T':
      return kT;
    case 'U':
      return kU;
    case 'V':
      return kV;
    case 'W':
      return kW;
    case 'X':
      return kX;
    case 'Y':
      return kY;
    case 'Z':
      return kZ;
    case '0':
      return k0;
    case '1':
      return k1;
    case '2':
      return k2;
    case '3':
      return k3;
    case '4':
      return k4;
    case '5':
      return k5;
    case '6':
      return k6;
    case '7':
      return k7;
    case '8':
      return k8;
    case '9':
      return k9;
    default:
      return kQuestion;
  }
}
